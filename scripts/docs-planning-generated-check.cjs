#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const repoRoot = path.resolve(__dirname, '..');

const EXPECTED_ARTIFACTS = [
  {
    path: 'docs/planning/index.md',
    markers: [
      /^title:\s*Planning$/m,
      /^# Planning$/m,
      /This page is auto-generated by `pnpm docs:sync`\./,
    ],
  },
  {
    path: 'docs/planning/proposals/index.md',
    markers: [
      /^title:\s*Planning Proposals$/m,
      /^# Planning Proposals$/m,
      /This page is auto-generated by `pnpm docs:sync`\./,
    ],
  },
  {
    path: 'docs/planning/reviews/index.md',
    markers: [
      /^title:\s*Planning Reviews$/m,
      /^# Planning Reviews$/m,
      /This page is auto-generated by `pnpm docs:sync`\./,
    ],
  },
  {
    path: 'docs/planning/status/index.md',
    markers: [
      /^title:\s*Planning Status$/m,
      /^# Planning Status$/m,
      /This page is auto-generated by `pnpm docs:sync`\./,
    ],
  },
  ...['a', 'b', 'c', 'd', 'e'].map((lane) => ({
    path: `docs/planning/state/agent-lane-${lane}.md`,
    markers: [
      /^planning_type:\s*status$/m,
      /Generated from the verified lane registry/,
      /^## Goal$/m,
      /^## Verification Summary$/m,
      /^## Tasks$/m,
    ],
  })),
  {
    path: 'docs/planning/state/execution-workboard.md',
    markers: [
      /^title:\s*Execution Workboard$/m,
      /This file is generated by `pnpm docs:workboard:generate`\./,
      /^# Execution Workboard$/m,
      /^## Lane Verification Snapshot$/m,
      /^## Active Work Items$/m,
    ],
  },
  {
    path: 'docs/planning/state/open-task-route.md',
    markers: [
      /^title:\s*Open Task Route$/m,
      /This file is generated by `pnpm docs:workboard:generate`\./,
      /^# Open Task Route$/m,
      /^## Current Open Snapshot$/m,
      /^## Actionable Now \(Strictly Unblocked\)$/m,
    ],
  },
];

const EXTRACTED_TRACKED_PATHS = [
  'docs/planning/index.md',
  'docs/planning/proposals/index.md',
  'docs/planning/reviews/index.md',
  'docs/planning/status/index.md',
  ...['a', 'b', 'c', 'd', 'e'].map((lane) => `docs/planning/state/agent-lane-${lane}.md`),
  'docs/planning/state/execution-workboard.md',
  'docs/planning/state/open-task-route.md',
];

function resolveCommand(command) {
  if (
    process.platform === 'win32' &&
    ['pnpm', 'npm', 'npx'].includes(command) &&
    !command.endsWith('.cmd') &&
    !command.endsWith('.exe')
  ) {
    return `${command}.cmd`;
  }
  return command;
}

function quoteWindowsArg(arg) {
  if (!/[ \t"&()^<>|]/.test(arg)) {
    return arg;
  }
  return `"${arg.replace(/"/g, '\\"')}"`;
}

function runCommand(command, args) {
  console.log(`> ${command} ${args.join(' ')}`.trim());
  const resolved = resolveCommand(command);
  const result =
    process.platform === 'win32' && resolved.endsWith('.cmd')
      ? spawnSync(
          process.env.ComSpec || 'cmd.exe',
          ['/d', '/s', '/c', [resolved, ...args].map(quoteWindowsArg).join(' ')],
          { cwd: repoRoot, stdio: 'inherit' }
        )
      : spawnSync(resolved, args, { cwd: repoRoot, stdio: 'inherit', shell: false });

  if (result.error) {
    throw result.error;
  }

  if (result.status !== 0) {
    process.exit(result.status || 1);
  }
}

function generatePlanningArtifacts() {
  runCommand('pnpm', ['docs:sync']);
  runCommand('pnpm', ['docs:workboard:generate']);
}

function assertNotTrackedInGit(relativePath) {
  const resolved = resolveCommand('git');
  const result = spawnSync(resolved, ['ls-files', '--error-unmatch', relativePath], {
    cwd: repoRoot,
    stdio: 'ignore',
    shell: false,
  });

  if (result.status === 0) {
    throw new Error(`Planning generated artifact must not be tracked in git: ${relativePath}`);
  }
}

function readArtifact(relativePath) {
  const absolutePath = path.join(repoRoot, relativePath);
  if (!fs.existsSync(absolutePath)) {
    throw new Error(`Missing generated planning artifact: ${relativePath}`);
  }
  return fs.readFileSync(absolutePath, 'utf8');
}

function assertMarkers(relativePath, content, markers) {
  for (const marker of markers) {
    if (!marker.test(content)) {
      throw new Error(
        `Generated planning artifact is malformed: ${relativePath} is missing marker ${marker}`
      );
    }
  }
}

function snapshotArtifacts() {
  const snapshot = new Map();
  for (const artifact of EXPECTED_ARTIFACTS) {
    const content = readArtifact(artifact.path);
    assertMarkers(artifact.path, content, artifact.markers);
    snapshot.set(artifact.path, content);
  }
  return snapshot;
}

function compareSnapshots(first, second) {
  const changed = [];
  for (const [artifactPath, firstContent] of first.entries()) {
    const secondContent = second.get(artifactPath);
    if (secondContent !== firstContent) {
      changed.push(artifactPath);
    }
  }

  if (changed.length > 0) {
    throw new Error(
      `Planning artifact generation is non-deterministic across repeated runs: ${changed.join(', ')}`
    );
  }
}

function main() {
  generatePlanningArtifacts();
  for (const trackedPath of EXTRACTED_TRACKED_PATHS) {
    assertNotTrackedInGit(trackedPath);
  }
  const firstSnapshot = snapshotArtifacts();
  generatePlanningArtifacts();
  const secondSnapshot = snapshotArtifacts();
  compareSnapshots(firstSnapshot, secondSnapshot);
  console.log(
    '[docs:planning:generated:check] Planning generated artifacts are present and deterministic.'
  );
}

main();
