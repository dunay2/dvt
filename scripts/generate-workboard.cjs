#!/usr/bin/env node
/* eslint-disable no-console */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const yaml = require('js-yaml');
const { resolveGeneratedDate } = require('./generated-doc-date.cjs');

const repoRoot = path.resolve(__dirname, '..');
const stateDir = path.join(repoRoot, 'docs', 'planning', 'state');
const workboardPath = path.join(stateDir, 'execution-workboard.md');
const openTaskPath = path.join(stateDir, 'open-task-route.md');

// ── Lane domain label (human-readable, used in workboard Domain column) ────
const LANE_DOMAIN = {
  A: 'Execution Runtime',
  B: 'Event Contract And Traceability',
  C: 'Runtime Safety And Admission',
  D: 'Scale And Go-To-Market',
};

function loadLanes() {
  const laneFiles = fs
    .readdirSync(stateDir)
    .filter((f) => /^agent-lane-[a-z]\.yaml$/.test(f))
    .sort();

  return laneFiles.map((file) => {
    const raw = fs.readFileSync(path.join(stateDir, file), 'utf8');
    return yaml.load(raw);
  });
}

/** Collect all tasks across lanes, each augmented with lane metadata. */
function collectTasks(lanes) {
  const tasks = [];
  for (const lane of lanes) {
    for (const task of lane.tasks ?? []) {
      tasks.push({
        ...task,
        lane_id: lane.lane_id,
        lane_title: lane.title,
        domain: LANE_DOMAIN[lane.lane_id] ?? lane.title,
      });
    }
  }
  return tasks;
}

/** Build a Set of all task_ids that are done, to evaluate dependency resolution. */
function buildDoneSet(tasks) {
  return new Set(tasks.filter((t) => t.status === 'done').map((t) => t.task_id));
}

/**
 * A task is unblocked when:
 *   - status is 'queued'
 *   - dependency is none/null/undefined OR all listed dependencies are done
 */
function isUnblocked(task, doneSet) {
  if (task.status !== 'queued') return false;
  const dep = task.dependency;
  if (!dep || dep === 'none') return true;
  // dependency field may be a string like "S02" or "S05, S02" or "S05 merge"
  // Split by comma or "and", strip whitespace, check each token
  const tokens = dep
    .split(/,|\band\b/)
    .map((s) => s.trim().split(/\s+/)[0]) // take first word only (e.g. "S16 merge" → "S16")
    .filter(Boolean);
  return tokens.every((t) => doneSet.has(t));
}

function pad(s, len) {
  return String(s).padEnd(len);
}

function buildWorkboard(tasks, date) {
  const statusOrder = { in_progress: 0, review: 1, queued: 2, blocked: 3, done: 4 };
  const sorted = [...tasks].sort((a, b) => {
    const sa = statusOrder[a.status] ?? 9;
    const sb = statusOrder[b.status] ?? 9;
    if (sa !== sb) return sa - sb;
    const pa = parseInt(String(a.priority ?? 'P9').replace('P', ''), 10);
    const pb = parseInt(String(b.priority ?? 'P9').replace('P', ''), 10);
    return pa - pb;
  });

  const rows = sorted.map((t) => [
    `\`${t.task_id}\``,
    String(t.objective ?? '').replace(/\n/g, ' '),
    t.domain,
    t.lane_title,
    String(t.dependency ?? 'none'),
    t.status,
    String(t.target ?? '').replace(/\n/g, ' '),
  ]);

  // Column widths
  const headers = ['Task ID', 'Objective', 'Domain', 'Lane', 'Dependencies', 'Status', 'Next action'];
  const widths = headers.map((h, i) =>
    Math.max(h.length, ...rows.map((r) => (r[i] ?? '').length))
  );

  const sep = widths.map((w) => '-'.repeat(w));
  const fmt = (row) => '| ' + row.map((c, i) => pad(c, widths[i])).join(' | ') + ' |';

  const lines = [
    '---',
    'title: Execution Workboard',
    'status: generated',
    'owner: generated',
    `last_reviewed: ${date}`,
    'planning_type: status',
    '---',
    '',
    '<!-- This file is generated by `pnpm docs:workboard:generate`. Do not edit by hand. -->',
    '',
    '# Execution Workboard',
    '',
    `Generated from agent-lane YAML files on ${date}.`,
    '',
    '## Status Legend',
    '',
    '- `in_progress`: active implementation.',
    '- `review`: in PR/review or merge validation.',
    '- `queued`: agreed but not started.',
    '- `blocked`: cannot proceed until dependencies close.',
    '- `done`: closed with evidence.',
    '',
    '## Active Work Items',
    '',
    fmt(headers),
    fmt(sep),
    ...rows.map(fmt),
    '',
  ];

  return lines.join('\n');
}

function buildOpenTaskRoute(tasks, doneSet, date) {
  const unblocked = tasks.filter((t) => isUnblocked(t, doneSet));
  const priorityOrder = (p) => parseInt(String(p ?? 'P9').replace('P', ''), 10);
  unblocked.sort((a, b) => priorityOrder(a.priority) - priorityOrder(b.priority));

  const inProgress = tasks.filter((t) => t.status === 'in_progress');
  const review = tasks.filter((t) => t.status === 'review');

  const counts = {
    in_progress: tasks.filter((t) => t.status === 'in_progress').length,
    review: tasks.filter((t) => t.status === 'review').length,
    queued: tasks.filter((t) => t.status === 'queued').length,
    blocked: tasks.filter((t) => t.status === 'blocked').length,
  };

  const fmtRow = (t) =>
    `| \`${t.priority ?? '-'}\` | \`${t.task_id}\` | ${String(t.objective ?? '').replace(/\n/g, ' ')} | ${String(t.target ?? '').replace(/\n/g, ' ')} |`;

  const activeSection = (label, list) => {
    if (list.length === 0) return [];
    return [
      `### ${label}`,
      '',
      '| Priority | Task ID | Objective | Next action |',
      '| -------- | ------- | --------- | ----------- |',
      ...list.map(fmtRow),
      '',
    ];
  };

  const lines = [
    '---',
    'title: Open Task Route',
    'status: generated',
    'owner: generated',
    `last_reviewed: ${date}`,
    'planning_type: status',
    '---',
    '',
    '<!-- This file is generated by `pnpm docs:workboard:generate`. Do not edit by hand. -->',
    '',
    '# Open Task Route',
    '',
    `Fast execution route for selecting the next task. Generated on ${date}.`,
    '',
    'Authoritative task source: [agent-lane YAML files](./agent-lane-a.yaml).',
    '',
    '## Current Open Snapshot',
    '',
    `- \`in_progress\`: ${counts.in_progress}`,
    `- \`review\`: ${counts.review}`,
    `- \`queued\`: ${counts.queued}`,
    `- \`blocked\`: ${counts.blocked}`,
    '- `done`: tracked in closeouts and evidence (not listed here)',
    '',
    '## Active',
    '',
    ...activeSection('In Progress', inProgress),
    ...activeSection('In Review', review),
    '## Actionable Now (Strictly Unblocked)',
    '',
    '| Priority | Task ID | Objective | Next action |',
    '| -------- | ------- | --------- | ----------- |',
    ...unblocked.map(fmtRow),
    '',
  ];

  return lines.join('\n');
}

function main() {
  const lanes = loadLanes();
  const tasks = collectTasks(lanes);
  const doneSet = buildDoneSet(tasks);

  const workboardContent = buildWorkboard(tasks, '');
  const openTaskContent = buildOpenTaskRoute(tasks, doneSet, '');

  const workboardDate = resolveGeneratedDate(workboardPath, (d) => buildWorkboard(tasks, d));
  const openTaskDate = resolveGeneratedDate(openTaskPath, (d) =>
    buildOpenTaskRoute(tasks, doneSet, d)
  );

  const finalWorkboard = buildWorkboard(tasks, workboardDate);
  const finalOpenTask = buildOpenTaskRoute(tasks, doneSet, openTaskDate);

  fs.writeFileSync(workboardPath, finalWorkboard, 'utf8');
  fs.writeFileSync(openTaskPath, finalOpenTask, 'utf8');

  console.log('[docs:workboard:generate] Updated execution-workboard.md and open-task-route.md');
}

main();
