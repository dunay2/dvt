#!/usr/bin/env node
/** Owned concern: render DB surface inventory from Planning DB authority rows. */
const fs = require('node:fs');
const path = require('node:path');
const { Client } = require('pg');

const { defaultPgUrl } = require('./planning-db-run.cjs');
const { sourceView } = require('./planning-db/db-surface-inventory.cjs');
const { textValue } = require('./planning-db/query-format.cjs');

const repoRoot = path.resolve(__dirname, '..');
const defaultOutputPath = path.join(
  repoRoot,
  '.generated-docs',
  'planning',
  'status',
  'generated-db-surface-inventory.md'
);
const migrationStateOrder = [
  'DB-first',
  'Hybrid indexed',
  'Bootstrap/export',
  'Generated-only',
  'Git-first indexed',
];

function databaseUrl() {
  return process.env.DVT_PLANNING_DB_URL || process.env.DATABASE_URL || defaultPgUrl;
}

function toPosix(filePath) {
  return filePath.replace(/\\/g, '/');
}

function relFromRepo(filePath) {
  return toPosix(path.relative(repoRoot, filePath));
}

function numericValue(value) {
  const parsed = Number(value ?? 0);
  return Number.isFinite(parsed) ? parsed : 0;
}

function booleanValue(value) {
  return value === true || value === 'true';
}

function markdownCell(value) {
  return textValue(value).replace(/\\/g, '\\\\').replace(/\|/g, '\\|');
}

function markdownTable(headers, rows) {
  return [
    `| ${headers.map(markdownCell).join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map(markdownCell).join(' | ')} |`),
  ].join('\n');
}

function migrationStateRank(state) {
  const index = migrationStateOrder.indexOf(state);
  return index === -1 ? migrationStateOrder.length : index;
}

function buildDbSurfaceInventorySelect() {
  return `
    select
      surface_name,
      canonical_source,
      write_rail,
      write_rail_kind,
      read_query_rail,
      projection,
      validation,
      migration_state,
      source_ref,
      source_content_sha256,
      revision,
      updated_by,
      db_first_eligible,
      db_first_blocker
    from ${sourceView}
    order by
      case migration_state
        when 'DB-first' then 1
        when 'Hybrid indexed' then 2
        when 'Bootstrap/export' then 3
        when 'Generated-only' then 4
        when 'Git-first indexed' then 5
        else 6
      end,
      surface_name`;
}

function normalizeDbSurfaceRow(row) {
  return {
    surfaceName: textValue(row.surface_name ?? row.surfaceName),
    canonicalSource: textValue(row.canonical_source ?? row.canonicalSource),
    writeRail: textValue(row.write_rail ?? row.writeRail),
    writeRailKind: textValue(row.write_rail_kind ?? row.writeRailKind),
    readQueryRail: textValue(row.read_query_rail ?? row.readQueryRail),
    projection: textValue(row.projection),
    validation: textValue(row.validation),
    migrationState: textValue(row.migration_state ?? row.migrationState),
    sourceRef: textValue(row.source_ref ?? row.sourceRef),
    sourceContentSha256: textValue(row.source_content_sha256 ?? row.sourceContentSha256),
    revision: numericValue(row.revision),
    updatedBy: textValue(row.updated_by ?? row.updatedBy),
    dbFirstEligible: booleanValue(row.db_first_eligible ?? row.dbFirstEligible),
    dbFirstBlocker: textValue(row.db_first_blocker ?? row.dbFirstBlocker, ''),
  };
}

function sortDbSurfaceRows(rows) {
  return [...rows].map(normalizeDbSurfaceRow).sort((left, right) => {
    return (
      migrationStateRank(left.migrationState) - migrationStateRank(right.migrationState) ||
      left.surfaceName.localeCompare(right.surfaceName)
    );
  });
}

function buildSummaryRows(rows) {
  const states = new Map(migrationStateOrder.map((state) => [state, 0]));
  let dbFirstEligible = 0;

  for (const row of rows) {
    states.set(row.migrationState, (states.get(row.migrationState) || 0) + 1);
    if (row.dbFirstEligible) {
      dbFirstEligible += 1;
    }
  }

  return [
    ['Total surfaces', String(rows.length)],
    ['DB-first eligible surfaces', String(dbFirstEligible)],
    ...migrationStateOrder.map((state) => [state, String(states.get(state) || 0)]),
  ];
}

function renderDbSurfaceInventory(rows) {
  const sortedRows = sortDbSurfaceRows(rows);

  return [
    '---',
    'title: Generated DB Surface Inventory',
    'status: Active',
    'owner: Architecture / Planning DB',
    'planning_type: status',
    '---',
    '',
    '# Generated DB Surface Inventory',
    '',
    '> This page is auto-generated by `pnpm docs:db-surface-inventory:generate`. Do not edit manually.',
    '',
    `Source view: \`${sourceView}\`.`,
    '',
    'The tracked status page is only a stable navigation pointer. This local render is the DB-first reading surface for DB governance surface state.',
    '',
    '## Summary',
    '',
    markdownTable(['Metric', 'Value'], buildSummaryRows(sortedRows)),
    '',
    '## Query Shortcuts',
    '',
    '- `pnpm planning:db:query db-surfaces --limit 30`',
    '- `pnpm planning:db:query db-surfaces --state DB-first --limit 30`',
    '- `pnpm planning:db:query db-surfaces --kind db_command --limit 30`',
    '',
    '## Surfaces',
    '',
    markdownTable(
      [
        'Surface',
        'Migration state',
        'Write rail kind',
        'DB-first eligible',
        'Read/query rail',
        'Projection',
        'Validation',
        'Source ref',
        'Revision',
      ],
      sortedRows.map((row) => [
        row.surfaceName,
        row.migrationState,
        row.writeRailKind,
        row.dbFirstEligible ? 'true' : 'false',
        row.readQueryRail,
        row.projection,
        row.validation,
        `\`${row.sourceRef}\``,
        String(row.revision),
      ])
    ),
    '',
  ].join('\n');
}

async function readDbSurfaceInventoryRows(client) {
  const result = await client.query(buildDbSurfaceInventorySelect());
  return result.rows;
}

function writeIfChanged(filePath, content) {
  const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null;
  if (current === content) {
    return false;
  }

  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
  return true;
}

async function runDbSurfaceInventoryGenerator(options = {}) {
  const outputPath = path.resolve(options.outputPath || defaultOutputPath);
  const client =
    options.client || new Client({ connectionString: options.databaseUrl || databaseUrl() });
  const ownsClient = !options.client;
  const logger = options.logger || console;

  if (ownsClient) {
    await client.connect();
  }

  try {
    const rows = await readDbSurfaceInventoryRows(client);
    const content = renderDbSurfaceInventory(rows);
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : null;
    const changed = current !== content;

    if (options.check) {
      if (changed) {
        throw new Error(
          `${relFromRepo(outputPath)} is stale. Run pnpm docs:db-surface-inventory:generate.`
        );
      }
      logger.log(
        `[docs:db-surface-inventory:check] ${relFromRepo(outputPath)} already up to date.`
      );
      return { changed: false, outputPath, rowCount: rows.length };
    }

    const wrote = writeIfChanged(outputPath, content);
    logger.log(
      wrote
        ? `[docs:db-surface-inventory:generate] Updated ${relFromRepo(outputPath)}`
        : `[docs:db-surface-inventory:generate] ${relFromRepo(outputPath)} already up to date.`
    );
    return { changed: wrote, outputPath, rowCount: rows.length };
  } finally {
    if (ownsClient) {
      await client.end();
    }
  }
}

function parseArgs(argv = process.argv.slice(2)) {
  const options = {};

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--check') {
      options.check = true;
      continue;
    }
    if (arg === '--output') {
      const value = argv[index + 1];
      if (!value || value.startsWith('--')) {
        throw new Error('--output requires a path.');
      }
      options.outputPath = value;
      index += 1;
      continue;
    }
    if (arg === '--help' || arg === '-h') {
      options.help = true;
      continue;
    }
    throw new Error(`Unknown docs:db-surface-inventory option "${arg}".`);
  }

  return options;
}

function printHelp() {
  console.log('Usage: pnpm docs:db-surface-inventory:generate [--check] [--output <path>]');
}

async function main() {
  const options = parseArgs();
  if (options.help) {
    printHelp();
    return;
  }
  await runDbSurfaceInventoryGenerator(options);
}

if (require.main === module) {
  main().catch((error) => {
    console.error(`[docs:db-surface-inventory] ${error.message || error}`);
    process.exit(1);
  });
}

module.exports = {
  buildDbSurfaceInventorySelect,
  defaultOutputPath,
  normalizeDbSurfaceRow,
  parseArgs,
  readDbSurfaceInventoryRows,
  renderDbSurfaceInventory,
  runDbSurfaceInventoryGenerator,
  sortDbSurfaceRows,
};
